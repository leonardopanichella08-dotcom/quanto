_FONTE_B = """
-- Fonte B: tabelle ufficiali versionate per data di validità (Modulo 9.2). Nessun valore è scritto nel codice.
CREATE TABLE fonte_b_datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('CCNL', 'PARAMS', 'AMORTIZATION', 'BENCHMARK')),
    code TEXT NOT NULL,                                 -- CCNL: sigla del contratto; altri tipi: nome breve dell'insieme
    name TEXT NOT NULL,
    version TEXT NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE,
    status TEXT NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'SUPERSEDED')),
    official BOOLEAN NOT NULL DEFAULT FALSE,            -- il manager attesta che i valori sono quelli della fonte indicata
    source_name TEXT NOT NULL,
    source_url TEXT,
    source_ref TEXT,
    file_name TEXT,
    file_sha256 TEXT,
    file_data BYTEA,
    notes TEXT,
    created_by TEXT NOT NULL,
    created_at TEXT NOT NULL,
    published_by TEXT,
    published_at TEXT,
    UNIQUE (kind, code, version),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE TABLE fonte_b_ccnl (
    dataset_id BIGINT NOT NULL REFERENCES fonte_b_datasets (id) ON DELETE CASCADE,
    level TEXT NOT NULL,
    standard_hours INTEGER NOT NULL CHECK (standard_hours > 0),
    social_charges_pct NUMERIC(7, 4) NOT NULL CHECK (social_charges_pct >= 0 AND social_charges_pct < 1),
    tfr_pct NUMERIC(7, 4) NOT NULL CHECK (tfr_pct >= 0 AND tfr_pct < 1),
    PRIMARY KEY (dataset_id, level)
);
CREATE TABLE fonte_b_params (
    dataset_id BIGINT NOT NULL REFERENCES fonte_b_datasets (id) ON DELETE CASCADE,
    param_key TEXT NOT NULL,
    value NUMERIC(18, 6) NOT NULL,
    unit TEXT,
    PRIMARY KEY (dataset_id, param_key)
);
CREATE TABLE fonte_b_amort (
    dataset_id BIGINT NOT NULL REFERENCES fonte_b_datasets (id) ON DELETE CASCADE,
    category_code TEXT NOT NULL,
    description TEXT,
    rate_pct NUMERIC(7, 4) NOT NULL CHECK (rate_pct > 0 AND rate_pct <= 1),
    PRIMARY KEY (dataset_id, category_code)
);
CREATE TABLE fonte_b_benchmarks (
    dataset_id BIGINT NOT NULL REFERENCES fonte_b_datasets (id) ON DELETE CASCADE,
    bench_kind TEXT NOT NULL CHECK (bench_kind IN ('PRICE', 'DAILY_RATE')),
    category_code TEXT NOT NULL,
    description TEXT,
    reference_eur NUMERIC(18, 2) NOT NULL CHECK (reference_eur > 0),
    PRIMARY KEY (dataset_id, bench_kind, category_code)
);
"""

